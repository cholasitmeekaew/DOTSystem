-- ---------------------------------------------------------------
-- ขั้นที่ 1: ดูก่อน — จะลบกี่รายการ แยกตามกฎอะไร
-- ---------------------------------------------------------------
select
  split_part(m.mark_key, ':', 1) as rule,
  count(*)                        as orphaned_marks,
  sum(m.delta)                    as points_that_were_lost
from points_award_marks m
where not exists (
  select 1
  from officers o
  where o.id = m.officer_id
    and exists (
      select 1
      from jsonb_array_elements(coalesce(o.points_log, '[]'::jsonb)) e
      where e->>'reason' = m.reason
    )
)
group by 1
order by 2 desc;


