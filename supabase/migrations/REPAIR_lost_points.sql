-- วิธีแก้
-- ───────
-- ลบเฉพาะ mark ที่ "ไม่มีรายการตรงกันในประวัติ" ทิ้ง
-- แล้วกดปุ่มสแกนคะแนนอีกครั้ง ระบบจะคำนวณใหม่ตามกฎปัจจุบัน
-- และเขียนประวัติลง points_log ครบถ้วน
--
-- mark ที่มีรายการตรงกันอยู่แล้วจะไม่ถูกแตะ (กันคะแนนซ้ำ)
