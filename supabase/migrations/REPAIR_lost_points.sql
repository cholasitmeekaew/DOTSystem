select count(*) as remaining_orphans
from points_award_marks m
where not exists (
  select 1
  from officers o
  where o.id = m.officer_id
    and exists (
      select 1
      from jsonb_array_elements(coalesce(o.points_log, '[]'::jsonb)) e
      where e->>'reason' = m.reason
    )
);


